export const getGradeNumberFromClass = (kelasName: string): number => {
  if (!kelasName) return 6;
  const match = kelasName.match(/(\d+)/);
  if (match) {
    const num = parseInt(match[1], 10);
    if (num >= 1 && num <= 6) return num;
  }
  return 6;
};

